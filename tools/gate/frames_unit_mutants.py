#!/usr/bin/env python3
"""frames_unit_mutants.py: the M6-M12 mutant lists through the frame gate (PLAN M13 "Mutants"; make frames-unit-mutants,
tools/gate/gate_frames_off.sh --unit-mutants).

    tools/gate/frames_unit_mutants.py --cases <case list> --jobs N --out <mutants file> <lists>
    tools/gate/frames_unit_mutants.py --report <mutants.py log> --out <mutants file> <lists>

<lists>: lines "<milestone> <mutants file>" (tb/frames/unit_mutant_lists.txt). The first form writes one mutants file
(tools/gate/mutants.py's format) on the whole RTL tree (@dir rtl/v1 RTLV1: every unit folder's default is under it, so
one control stands for all), @obj P2OFF_OBJDIR, one probe: frames_mprobe --jobs N <case list> (the frame subset's
captures, cheapest first, the base configuration; tools/gate/frames_mprobe.sh). Each mutant of the lists keeps its file,
fragments and description; its id becomes <list tag>.<id> (the tag: the list's unit and file, e.g. isp_tile.m7); a
mutant that must pass its own probe (!<probe>) must pass this one too. A mutant whose folder is not part of p2-offline's
build (its file not among make's P2_CORE_LIB / P2_CORE_SRC, e.g. tools/gen's generators) is left out and listed.
Prints "frames-unit-mutants: ..." lines (the counts per list).

The second form reads mutants.py's verdicts and prints, per milestone and list, the mutants the frame subset caught
and those only their own unit gate catches, each with its description and the reason (tb/frames/unit_mutant_reasons.txt:
"<id> | <reason>", the analysis of the survivors; a survivor without a reason is reported as "no reason recorded").
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "tools", "gate"))
import mutants as M  # noqa: E402


def lists(path):
    out = []
    for line in open(path):
        f = line.split("#")[0].split()
        if len(f) >= 2:
            out.append((f[0], f[1]))
    return out


def tag_of(path):
    unit = os.path.basename(os.path.dirname(path))
    base = os.path.basename(path)[:-4]
    return unit + ("" if base == "mutants" else "." + base[len("mutants_"):])


def core_files():
    with tempfile.NamedTemporaryFile("w", suffix=".mk", delete=False) as t:
        t.write("p2-print-core-src: ; @echo $(P2_CORE_LIB) $(P2_CORE_SRC)\n")
        mk = t.name
    try:
        out = subprocess.run(["make", "-s", "-f", "Makefile", "-f", mk, "p2-print-core-src"], cwd=ROOT,
                             capture_output=True, text=True, check=True).stdout
    finally:
        os.unlink(mk)
    return {os.path.normpath(p) for p in out.split()}


def escape(s):
    return s.replace("\\", "\\\\").replace("\n", "\\n").replace("|", "\\|")


def build(a):
    core = core_files()
    out = [f"# generated by tools/gate/frames_unit_mutants.py from {a.lists}: the M6-M12 lists through the frame subset",
           "@dir rtl/v1 RTLV1", "@obj P2OFF_OBJDIR",
           f"@probe frames p2-offline-mprobe frames_mprobe --jobs {a.jobs} {a.cases}", ""]
    total = skipped = 0
    for ms, path in lists(a.lists):
        cfg = M.parse(os.path.join(ROOT, path))
        folder = cfg["dir"][0]
        tag = tag_of(path)
        n = k = 0
        for m in cfg["mutants"]:
            f = os.path.normpath(os.path.join(folder, m["file"]))
            if not f.startswith("rtl/v1/") or f not in core:
                k += 1
                print(f"frames-unit-mutants: {ms} {tag}.{m['id']}: not in p2_core's build ({f}): its own gate only")
                continue
            rel = os.path.relpath(f, "rtl/v1")
            probe = ("!" if m["pass"] else "") + "frames"
            out.append(" | ".join([f"{tag}.{m['id']}", rel, escape(m["orig"]), escape(m["mut"]), probe,
                                   escape(m["what"])]))
            n += 1
        total += n
        skipped += k
        print(f"frames-unit-mutants: {ms} {path}: {n} mutants" + (f", {k} not in p2_core's build" if k else ""))
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    open(a.out, "w").write("\n".join(out) + "\n")
    print(f"frames-unit-mutants: {total} mutants through the frame subset ({skipped} not in p2_core's build)")


def report(a):
    reasons = {}
    rf = os.path.join(ROOT, "tb", "frames", "unit_mutant_reasons.txt")
    if os.path.exists(rf):
        for line in open(rf):
            if line.strip() and not line.startswith("#") and "|" in line:
                i, r = line.split("|", 1)
                reasons[i.strip()] = r.strip()
    verdict = {}
    for line in open(a.report):
        m = re.match(r"^\S+-mutants: (\S+)\s+(caught|SURVIVED|passes, as it must|CAUGHT \(must pass\)|ERROR: .*?)\s+frames: (.*)$",
                     line.rstrip("\n"))
        if m:
            verdict[m[1]] = (m[2], m[3])
    merged = {m["id"] for m in M.parse(a.out)["mutants"]}
    tot = caught = 0
    for ms, path in lists(a.lists):
        cfg = M.parse(os.path.join(ROOT, path))
        tag = tag_of(path)
        ids = [f"{tag}.{m['id']}" for m in cfg["mutants"]]
        ran = [i for i in ids if i in verdict]
        c = [i for i in ran if verdict[i][0] in ("caught", "passes, as it must")]
        tot += len(ran)
        caught += len(c)
        nc = sum(1 for i in ids if i not in merged)
        nr = sum(1 for i in ids if i in merged and i not in verdict)
        print(f"frames-unit-mutants: {ms} {path}: {len(c)} of {len(ran)} caught by the frame subset"
              + (f"; {nc} not in p2_core's build (their own gate only)" if nc else "")
              + (f"; {nr} without a verdict" if nr else ""))
        for i in ran:
            v, what = verdict[i]
            if v not in ("caught", "passes, as it must"):
                print(f"frames-unit-mutants:   {i}: {v} (only its unit gate): {what}; reason: "
                      f"{reasons.get(i, 'no reason recorded')}")
    print(f"frames-unit-mutants: {caught} of {tot} caught by the frame subset, {tot - caught} only by their unit gates")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("lists")
    ap.add_argument("--cases")
    ap.add_argument("--jobs", type=int, default=8)
    ap.add_argument("--out", required=True)
    ap.add_argument("--report")
    a = ap.parse_args()
    if a.report:
        report(a)
    else:
        build(a)


if __name__ == "__main__":
    main()
